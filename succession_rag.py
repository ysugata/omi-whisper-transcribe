@dataclass
class KCSource:
    """A single sanitized knowledge card with session metadata."""

    session_id: str
    question: str
    answer: str
    evidence: list[str]
    confidence: str
    context: str = ""          # 1-sentence topic summary (generated at build)
    similarity: float = 0.0    # dense cosine score
    bm25_score: float = 0.0    # sparse BM25 score
    rrf_score: float = 0.0     # final fused rank score

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class SuccessionAnswer:
    """Response to a succession query."""

    query: str
    answer: str
    sources: list[KCSource]
    model: str
    elapsed_sec: float
    index_size: int
    warnings: list[str]
    retrieval_mode: str = "hybrid"  # "hybrid" / "dense_only" / "bm25_only"

    def to_dict(self) -> dict[str, Any]:
        return {
            "query": self.query,
            "answer": self.answer,
            "sources": [s.to_dict() for s in self.sources],
            "model": self.model,
            "elapsed_sec": self.elapsed_sec,
            "index_size": self.index_size,
            "warnings": self.warnings,
            "retrieval_mode": self.retrieval_mode,
        }


