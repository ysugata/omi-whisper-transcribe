# Tokenizer (CJK + ASCII)
# ---------------------------------------------------------------------------


# Split into ASCII words and character runs; then bigram the non-ASCII runs.
_TOKENIZE_SPLIT = re.compile(r"[A-Za-z0-9]+|[^\s\wA-Za-z0-9]|\w")


def _tokenize_cjk(text: str) -> list[str]:
    """Simple tokenizer suitable for mixed Japanese / ASCII BM25.

    - ASCII words → lowercased whole tokens
    - Non-ASCII characters → unigrams + bigrams (common CJK fallback)
    - Punctuation / whitespace → dropped
    """
    if not text:
        return []
    tokens: list[str] = []
    # Collect ASCII word tokens
    for m in re.finditer(r"[A-Za-z0-9]+", text):
        tokens.append(m.group(0).lower())
    # Collect CJK/hiragana/katakana/kanji characters only
    cjk = re.findall(r"[\u3040-\u309f\u30a0-\u30ff\u4e00-\u9fff]", text)
    if cjk:
        # unigrams
        tokens.extend(cjk)
        # bigrams
        for i in range(len(cjk) - 1):
            tokens.append(cjk[i] + cjk[i + 1])
    return tokens


