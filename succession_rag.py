"""Succession RAG — retrieval-augmented Q&A over sanitized knowledge cards.

Implements **Contextual Retrieval** (Anthropic, 2024) with hybrid fusion:

1. Each KC is enriched at build time with a short 1-sentence context
   describing what session/topic it came from, generated by gpt-5-nano.
2. Two indices are built: dense (gemini-embedding-001 over "context + Q")
   and sparse (BM25 over tokenized "context + Q").
3. At query time, both indices return top-K candidates which are fused
   via Reciprocal Rank Fusion (RRF) then passed to gpt-5-nano for answer
   generation grounded in the retrieved KCs.

This matches Anthropic's recommended pattern which reduces retrieval
failures by 49% (or 67% with reranking). See:
https://www.anthropic.com/news/contextual-retrieval

Design goals:
- Evidence-grounded: every answer cites the KCs it came from.
- Incremental: new sanitized sessions are picked up by rebuilding the index.
- Cost-minimal: gemini-embedding-001 + gpt-5-nano ≈ $1-2 / month.
- Fail-safe: if the LLM call fails, still return the retrieved KCs.

Persistence:
- `config/succession_index.npz` — dense embeddings
- `config/succession_index.json` — KC metadata + fingerprint + model info
- BM25 is rebuilt in-memory on load (cheap).
"""

