# RRF constant: smaller values weight the top of each list more heavily.
# 60 is the well-known default from the original RRF paper (Cormack et al.).
_RRF_K = 60


class SuccessionRAG:
    """Retrieval-augmented Q&A over sanitized knowledge cards.

    Hybrid retrieval: dense (embedding) + sparse (BM25), fused via RRF.
    Each KC is enriched with a short "context" sentence at build time
    (Anthropic's Contextual Retrieval technique).

    Thread-safety: build_index() and ask() each acquire an internal lock.
    Index data is swapped atomically so readers never see partial state.
    """

    def __init__(
        self,
        config_dir: str | Path,
        gemini_api_key: str,
        openai_api_key: str,
        embed_model: str = "gemini-embedding-001",
        answer_model: str = "gpt-5-nano",
        context_model: str = "gpt-5-nano",
        reasoning_effort: str = "low",
        max_output_tokens: int = 800,
        timeout_sec: float = 60.0,
        knowledge_dir: str | Path | None = None,
    ) -> None:
        self._config_dir = Path(config_dir)
        self._gemini_key = gemini_api_key
        self._openai_key = openai_api_key
        self._embed_model = embed_model
        self._answer_model = answer_model
        self._context_model = context_model
        self._reasoning_effort = reasoning_effort
        self._max_output_tokens = max_output_tokens
        self._timeout_sec = timeout_sec

        # Index state
        self._embeddings: Optional[np.ndarray] = None  # (N, D) L2-normalized
        self._sources: list[KCSource] = []
        self._bm25 = None  # rank_bm25.BM25Okapi instance
        self._bm25_corpus: list[list[str]] = []  # parallel to _sources
        self._fingerprint: str = ""
        self._index_version: int = 2  # bump when shape changes

        # Wiki parent index (Phase 2.5)
        self._wiki = WikiIndex(knowledge_dir) if knowledge_dir else None
        if self._wiki and self._wiki.enabled:
            try:
                self._wiki.load()
            except Exception as e:
                log.warning("WikiIndex initial load failed: %s", e)

        # Lazy clients
        self._genai_client = None
        self._openai_client = None

        # Persistent files
        self._npz_path = self._config_dir / "succession_index.npz"
        self._meta_path = self._config_dir / "succession_index.json"

        self._lock = threading.Lock()

        self._enabled = bool(gemini_api_key and openai_api_key)
        if not self._enabled:
            log.warning(
                "SuccessionRAG disabled: missing GEMINI_API_KEY or OPENAI_API_KEY"
            )

    # -- lifecycle -----------------------------------------------------------

    @property
    def enabled(self) -> bool:
        return self._enabled

    @property
    def index_size(self) -> int:
        return len(self._sources)

    def status(self) -> dict[str, Any]:
        wiki_status = self._wiki.status() if self._wiki else None
        # parent_child mode is automatic when wiki has data; otherwise stay on KC-only hybrid
        if self._wiki and self._wiki.topic_count > 0:
            mode = "parent_child"
        elif self._bm25 is not None:
            mode = "hybrid_rrf"
        else:
            mode = "dense_only"
        return {
            "enabled": self._enabled,
            "index_size": self.index_size,
            "embed_model": self._embed_model,
            "answer_model": self._answer_model,
            "context_model": self._context_model,
            "fingerprint": self._fingerprint,
            "index_path": str(self._npz_path),
            "index_version": self._index_version,
            "retrieval_mode": mode,
            "wiki": wiki_status,
            "ready": self._embeddings is not None and len(self._sources) > 0,
        }

    def reload_wiki(self) -> dict[str, Any]:
        """Reload the wiki index from disk (called after host-side build_wiki.py runs)."""
        if self._wiki is None:
            return {"status": "disabled"}
        return self._wiki.load()

    # -- client helpers ------------------------------------------------------

    def _get_genai_client(self):
        if self._genai_client is None:
            from google import genai
            self._genai_client = genai.Client(api_key=self._gemini_key)
        return self._genai_client

    def _get_openai_client(self):
        if self._openai_client is None:
            from openai import OpenAI
            self._openai_client = OpenAI(
                api_key=self._openai_key,
                timeout=self._timeout_sec,
            )
        return self._openai_client

    # -- index build / persistence ------------------------------------------

    @staticmethod
    def _compute_fingerprint(sources: list[KCSource]) -> str:
        """Stable hash of (session_id, question, answer, context) tuples."""
        h = hashlib.sha256()
        for s in sources:
            h.update(s.session_id.encode("utf-8"))
            h.update(b"\x1f")
            h.update(s.question.encode("utf-8"))
            h.update(b"\x1e")
            h.update(s.answer.encode("utf-8"))
            h.update(b"\x1d")
            h.update((s.context or "").encode("utf-8"))
            h.update(b"\n")
        return h.hexdigest()

    def _collect_sources(self) -> tuple[list[KCSource], dict[str, str]]:
        """Walk config/safe_training_*.jsonl via SanitizedIndex.

        Returns (sources, session_summaries) where session_summaries maps
        session_id → summary_output text, used as hint for contextualization.
        """
        idx = SanitizedIndex(self._config_dir)
        sources: list[KCSource] = []
        session_summaries: dict[str, str] = {}
        seen: set[tuple[str, str]] = set()

        for sid, bucket in idx._by_session.items():  # noqa: SLF001
            summary_out = bucket.get("summary_output") or ""
            if summary_out:
                session_summaries[sid] = summary_out

            for c in bucket.get("knowledge_cards") or []:
                q = (c.get("question") or "").strip()
                a = (c.get("answer") or "").strip()
                if not q or not a:
                    continue
                key = (sid, q)
                if key in seen:
                    continue
                seen.add(key)
                sources.append(KCSource(
                    session_id=sid,
                    question=q,
                    answer=a,
                    evidence=list(c.get("evidence") or []),
                    confidence=str(c.get("confidence") or "medium"),
                ))
        return sources, session_summaries

    def _contextualize_one(
        self,
        kc: KCSource,
        session_summary: str,
    ) -> str:
        """Generate a short topic context for a single KC via gpt-5-nano."""
        client = self._get_openai_client()
        user_input = (
            f"## セッション要約\n{session_summary or '(要約なし)'}\n\n"
            f"## KC\nQ: {kc.question}\nA: {kc.answer}"
        )
        try:
            # max_output_tokens must accommodate reasoning tokens + the
            # actual text output. At effort="low" gpt-5-nano spends ~120-200
            # reasoning tokens, so 150 left zero budget for visible output.
            # 800 leaves headroom for ~600 reasoning + 200 output (the text
            # output itself is <=80 chars by instruction).
            response = client.responses.create(
                model=self._context_model,
                instructions=_CONTEXTUALIZE_INSTRUCTIONS,
                input=[{"role": "user", "content": user_input}],
                reasoning={"effort": "low"},
                max_output_tokens=800,
                store=False,
            )
            if response.status == "completed":
                text = (response.output_text or "").strip()
                # Truncate to 80 chars as a safety net
                return text[:80]
            elif response.status == "incomplete":
                reason = ""
                if response.incomplete_details:
                    reason = getattr(
                        response.incomplete_details, "reason", "unknown"
                    )
                log.warning(
                    "Contextualize incomplete for %s: %s",
                    kc.session_id, reason,
                )
        except Exception as e:
            log.warning(
                "Contextualize failed for %s: %s", kc.session_id, e
            )
        return ""

    def _contextualize_all(
        self,
        sources: list[KCSource],
        session_summaries: dict[str, str],
        reuse: dict[tuple[str, str], str] | None = None,
    ) -> None:
        """Populate `context` field on each KCSource in-place.

        `reuse` allows carrying over contexts from a previous build keyed on
        (session_id, question) so rebuilds after new sanitize runs only pay
        the LLM cost for new KCs.
        """
        reuse = reuse or {}
        new_count = 0
        for i, s in enumerate(sources):
            cached = reuse.get((s.session_id, s.question))
            if cached:
                s.context = cached
                continue
            s.context = self._contextualize_one(
                s, session_summaries.get(s.session_id, "")
            )
            new_count += 1
            if new_count % 20 == 0:
                log.info(
                    "SuccessionRAG: contextualized %d / %d KCs",
                    i + 1, len(sources),
                )
        log.info(
            "SuccessionRAG: contextualized %d new KCs (%d reused)",
            new_count, len(sources) - new_count,
        )

    def _embed_batch(self, texts: list[str]) -> np.ndarray:
        """Embed texts and return an (N, D) array of L2-normalized vectors."""
        client = self._get_genai_client()
        all_vecs: list[list[float]] = []
        BATCH = 100
        for i in range(0, len(texts), BATCH):
            chunk = texts[i:i + BATCH]
            result = client.models.embed_content(
                model=self._embed_model,
                contents=chunk,
            )
            for e in result.embeddings:
                all_vecs.append(list(e.values))
            log.info(
                "SuccessionRAG: embedded %d / %d",
                min(i + BATCH, len(texts)),
                len(texts),
            )
        arr = np.asarray(all_vecs, dtype=np.float32)
        norms = np.linalg.norm(arr, axis=1, keepdims=True)
        norms[norms == 0] = 1.0
        return arr / norms

    @staticmethod
    def _contextualized_text(s: KCSource) -> str:
        """The string used for both embedding and BM25 indexing."""
        if s.context:
            return f"{s.context} / {s.question}"
        return s.question

    def _build_bm25(self, sources: list[KCSource]) -> None:
        """Rebuild the in-memory BM25 index from current sources."""
        from rank_bm25 import BM25Okapi
        corpus = [_tokenize_cjk(self._contextualized_text(s)) for s in sources]
        # BM25Okapi raises on empty corpus
        if not corpus:
            self._bm25 = None
            self._bm25_corpus = []
            return
        self._bm25 = BM25Okapi(corpus)
        self._bm25_corpus = corpus

    def build_index(self, force: bool = False) -> dict[str, Any]:
        """Collect sources + contextualize + embed + BM25 + persist."""
        if not self._enabled:
            return {"status": "disabled"}

        t0 = time.time()
        sources, session_summaries = self._collect_sources()
        if not sources:
            with self._lock:
                self._sources = []
                self._embeddings = None
                self._bm25 = None
                self._bm25_corpus = []
                self._fingerprint = ""
            return {"status": "empty", "size": 0}

        # Build reuse cache from existing sources so new sanitize runs
        # only contextualize NEW KCs.
        reuse_ctx: dict[tuple[str, str], str] = {
            (s.session_id, s.question): s.context
            for s in self._sources
            if s.context
        }

        self._contextualize_all(sources, session_summaries, reuse=reuse_ctx)
        new_fp = self._compute_fingerprint(sources)

        if (
            not force
            and new_fp == self._fingerprint
            and self._embeddings is not None
            and self._bm25 is not None
        ):
            return {
                "status": "unchanged",
                "size": len(sources),
                "fingerprint": new_fp,
                "elapsed_sec": time.time() - t0,
            }

        log.info("SuccessionRAG: building hybrid index for %d KCs", len(sources))
        texts = [self._contextualized_text(s) for s in sources]
        embeddings = self._embed_batch(texts)

        with self._lock:
            self._sources = sources
            self._embeddings = embeddings
            self._fingerprint = new_fp
            self._build_bm25(sources)

        self._save()
        elapsed = time.time() - t0
        log.info(
            "SuccessionRAG: hybrid index built (%d KCs, dim=%d, %.2fs)",
            len(sources), embeddings.shape[1], elapsed,
        )
        return {
            "status": "built",
            "size": len(sources),
            "dim": int(embeddings.shape[1]),
            "fingerprint": new_fp,
            "retrieval_mode": "hybrid_rrf",
            "elapsed_sec": elapsed,
        }

    def _save(self) -> None:
        """Persist embeddings + metadata to disk. BM25 is recomputed on load."""
        try:
            self._config_dir.mkdir(parents=True, exist_ok=True)
            if self._embeddings is not None:
                np.savez_compressed(self._npz_path, embeddings=self._embeddings)
            meta = {
                "fingerprint": self._fingerprint,
                "embed_model": self._embed_model,
                "index_version": self._index_version,
                "sources": [s.to_dict() for s in self._sources],
            }
            self._meta_path.write_text(
                json.dumps(meta, ensure_ascii=False), encoding="utf-8"
            )
        except Exception as e:  # pragma: no cover
            log.error("SuccessionRAG: failed to persist index: %s", e)

    def load_index(self) -> bool:
        """Load persisted index if available. Rebuilds BM25 from sources."""
        if not (self._npz_path.exists() and self._meta_path.exists()):
            return False
        try:
            data = np.load(self._npz_path)
            embeddings = data["embeddings"]
            meta = json.loads(self._meta_path.read_text(encoding="utf-8"))
            version = meta.get("index_version", 1)
            sources = []
            for s in meta.get("sources", []):
                # Strip runtime-only fields that may be present in legacy dumps
                clean = {
                    k: v for k, v in s.items()
                    if k not in ("similarity", "bm25_score", "rrf_score")
                }
                # Ensure 'context' field exists even in v1 dumps
                clean.setdefault("context", "")
                sources.append(KCSource(**clean))
            if len(sources) != embeddings.shape[0]:
                log.warning(
                    "SuccessionRAG: index mismatch (%d sources vs %d embeddings)",
                    len(sources), embeddings.shape[0],
                )
                return False
            with self._lock:
                self._sources = sources
                self._embeddings = embeddings.astype(np.float32)
                self._fingerprint = meta.get("fingerprint", "")
                self._build_bm25(sources)
            log.info(
                "SuccessionRAG: loaded %d KCs (version=%d) from %s",
                len(sources), version, self._npz_path,
            )
            return True
        except Exception as e:
            log.error("SuccessionRAG: failed to load index: %s", e)
            return False

    # -- retrieval -----------------------------------------------------------

    def retrieve(self, query: str, k: int = 5) -> list[KCSource]:
        """Hybrid top-K retrieval (dense + BM25 fused via RRF)."""
        if self._embeddings is None or not self._sources:
            return []
        if not query.strip():
            return []

        n = len(self._sources)
        k = min(k, n)

        # Dense scores
        q_vec = self._embed_batch([query])[0]
        dense_scores = (self._embeddings @ q_vec).astype(np.float32)

        # Sparse scores
        if self._bm25 is not None:
            q_tokens = _tokenize_cjk(query)
            if q_tokens:
                sparse_scores = np.asarray(
                    self._bm25.get_scores(q_tokens), dtype=np.float32,
                )
            else:
                sparse_scores = np.zeros(n, dtype=np.float32)
        else:
            sparse_scores = np.zeros(n, dtype=np.float32)

        # Take top candidates from each (larger pool than final k so fusion
        # has more to work with). Typical practice: pool = 4 * k.
        pool = min(max(20, 4 * k), n)

        dense_top = np.argpartition(-dense_scores, pool - 1)[:pool]
        dense_top = dense_top[np.argsort(-dense_scores[dense_top])]

        if self._bm25 is not None and sparse_scores.max() > 0:
            sparse_top = np.argpartition(-sparse_scores, pool - 1)[:pool]
            sparse_top = sparse_top[np.argsort(-sparse_scores[sparse_top])]
        else:
            sparse_top = np.array([], dtype=int)

        # Reciprocal Rank Fusion
        rrf: dict[int, float] = {}
        for rank, idx in enumerate(dense_top, start=1):
            rrf[int(idx)] = rrf.get(int(idx), 0.0) + 1.0 / (_RRF_K + rank)
        for rank, idx in enumerate(sparse_top, start=1):
            rrf[int(idx)] = rrf.get(int(idx), 0.0) + 1.0 / (_RRF_K + rank)

        # Top k by RRF score
        fused = sorted(rrf.items(), key=lambda x: -x[1])[:k]

        results: list[KCSource] = []
        for idx, score in fused:
            src = self._sources[idx]
            results.append(KCSource(
                session_id=src.session_id,
                question=src.question,
                answer=src.answer,
                evidence=list(src.evidence),
                confidence=src.confidence,
                context=src.context,
                similarity=float(dense_scores[idx]),
                bm25_score=float(sparse_scores[idx]) if sparse_scores.size else 0.0,
                rrf_score=float(score),
            ))
        return results

    # -- parent-child retrieval (Phase 2.5) ----------------------------------

    def retrieve_with_wiki(
        self,
        query: str,
        k_kcs: int = 15,
        k_topics: int = 5,
    ) -> tuple[list[KCSource], list[WikiTopic]]:
        """LangChain Parent-Document-Retriever style:
            1. Hybrid retrieve k_kcs KCs (precision layer)
            2. Aggregate by parent wiki topic via session_id
            3. Return top k_topics topics + the kcs that matched them

        If the wiki index is empty/disabled, returns (kcs, []).
        """
        kcs = self.retrieve(query, k=k_kcs)
        if not kcs:
            return [], []
        if self._wiki is None or self._wiki.topic_count == 0:
            return kcs, []

        # Aggregate KCs by wiki topic. The score for a topic is the sum of
        # rrf_scores of its child KCs that hit, so a topic backed by 3
        # strong KCs ranks above a topic backed by 1.
        topic_scores: dict[int, float] = {}
        topic_match_counts: dict[int, int] = {}
        topic_kcs: dict[int, list[KCSource]] = {}

        for kc in kcs:
            for idx in self._wiki.topic_indices_for_session(kc.session_id):
                topic_scores[idx] = topic_scores.get(idx, 0.0) + kc.rrf_score
                topic_match_counts[idx] = topic_match_counts.get(idx, 0) + 1
                topic_kcs.setdefault(idx, []).append(kc)

        if not topic_scores:
            # No KC mapped to a wiki topic — wiki may be stale relative to
            # newly sanitized sessions. Fall back to KC-only.
            return kcs, []

        ranked = sorted(topic_scores.items(), key=lambda x: -x[1])[:k_topics]
        wiki_topics: list[WikiTopic] = []
        for idx, score in ranked:
            t = self._wiki.get_topic(idx)
            if t is None:
                continue
            # Return a *copy* so callers can mutate aggregate fields without
            # polluting the cached topic. WikiTopic is dataclass with simple
            # fields, asdict + new ctor would lose typing — copy by hand.
            copy = WikiTopic(
                path=t.path,
                visibility=t.visibility,
                title=t.title,
                domain=t.domain,
                body=t.body,
                sources=list(t.sources),
                confidence=t.confidence,
                status=t.status,
                manual=t.manual,
                aggregate_score=float(score),
                matched_kc_count=int(topic_match_counts.get(idx, 0)),
            )
            wiki_topics.append(copy)
        return kcs, wiki_topics

    # -- answer --------------------------------------------------------------

    def ask(self, query: str, k: int = 5) -> SuccessionAnswer:
        """Run the full RAG pipeline and return an answer + sources.

        If a wiki index is loaded, uses parent-child retrieval (Phase 2.5):
        retrieve_with_wiki returns top KCs aggregated by their parent wiki
        topic, and both are passed to the answer model. Otherwise falls
        back to KC-only hybrid retrieval (Phase 1.5).
        """
        t0 = time.time()
        warnings: list[str] = []
        wiki_loaded = self._wiki is not None and self._wiki.topic_count > 0
        if wiki_loaded:
            retrieval_mode = "parent_child"
        elif self._bm25 is not None:
            retrieval_mode = "hybrid"
        else:
            retrieval_mode = "dense_only"

        if not self._enabled:
            return SuccessionAnswer(
                query=query,
                answer="SuccessionRAG が無効です (API キー未設定)。",
                sources=[],
                model=self._answer_model,
                elapsed_sec=0.0,
                index_size=0,
                warnings=["disabled"],
                retrieval_mode=retrieval_mode,
            )

        if self._embeddings is None or not self._sources:
            return SuccessionAnswer(
                query=query,
                answer="インデックスが空です。先に /succession/rebuild を実行してください。",
                sources=[],
                model=self._answer_model,
                elapsed_sec=0.0,
                index_size=0,
                warnings=["empty_index"],
                retrieval_mode=retrieval_mode,
            )

        wiki_topics: list[WikiTopic] = []
        if wiki_loaded:
            # Pull a wider KC pool so we can aggregate to topic level
            sources, wiki_topics = self.retrieve_with_wiki(
                query, k_kcs=max(k * 3, 15), k_topics=k,
            )
            if not wiki_topics:
                # Wiki is loaded but none of the top KCs map to a topic
                # (e.g. wiki is stale). Fall back to KC-only display.
                warnings.append("wiki_no_match_fallback")
                # Trim sources to the requested k for output
                sources = sources[:k]
        else:
            sources = self.retrieve(query, k=k)

        if not sources:
            return SuccessionAnswer(
                query=query,
                answer="関連する KC が見つかりませんでした。",
                sources=[],
                model=self._answer_model,
                elapsed_sec=time.time() - t0,
                index_size=self.index_size,
                warnings=["no_sources"],
                retrieval_mode=retrieval_mode,
            )

        user_prompt = _build_user_prompt(query, sources, wiki_topics or None)

        try:
            client = self._get_openai_client()
            response = client.responses.create(
                model=self._answer_model,
                instructions=_SYSTEM_PROMPT,
                input=[{"role": "user", "content": user_prompt}],
                reasoning={"effort": self._reasoning_effort},
                max_output_tokens=self._max_output_tokens,
                store=False,
            )
        except Exception as e:
            log.error("SuccessionRAG: LLM call failed: %s", e)
            return SuccessionAnswer(
                query=query,
                answer=(
                    "LLM 呼び出しに失敗しました。以下の関連 KC を直接ご確認ください。"
                ),
                sources=sources,
                model=self._answer_model,
                elapsed_sec=time.time() - t0,
                index_size=self.index_size,
                warnings=[f"llm_error:{type(e).__name__}"],
                retrieval_mode=retrieval_mode,
            )

        if response.status == "incomplete":
            reason = ""
            if response.incomplete_details:
                reason = getattr(response.incomplete_details, "reason", "unknown")
            warnings.append(f"incomplete:{reason}")

        answer_text = (response.output_text or "").strip()
        if not answer_text:
            answer_text = "(回答が空でした。以下の関連 KC をご確認ください。)"
            warnings.append("empty_answer")

        return SuccessionAnswer(
            query=query,
            answer=answer_text,
            sources=sources,
            wiki_topics=wiki_topics,
            model=self._answer_model,
            elapsed_sec=time.time() - t0,
            index_size=self.index_size,
            warnings=warnings,
            retrieval_mode=retrieval_mode,
        )
