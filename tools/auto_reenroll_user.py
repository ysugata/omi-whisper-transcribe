#!/usr/bin/env python3
"""Auto re-enroll the user's voiceprint after an embedding-model change.

This tool is needed when speakers.json embeddings were generated by an older
model (e.g., pyannote/embedding) but the bridge now uses a newer model
(e.g., wespeaker-voxceleb-resnet34-LM). The old embeddings become
incompatible and every segment gets tagged as "unknown".

Strategy:
1. Scan recent sessions in recordings/
2. Filter for strong user-voice candidates:
   - PANNs scene_label_en == "conversation" (NOT "media")
   - PANNs music.detected == False
   - session.num_speakers == 1
   - duration_seconds between MIN_DURATION and MAX_DURATION
3. Pick the N most recent qualifying sessions
4. Clear existing samples on the is_user speaker
5. Add voiceprint from each candidate → rebuild centroid embedding
6. Update speakers.json model field to current model name

Run inside the container so HF_AUTH_TOKEN + GPU are available:

    docker compose exec omi-whisper python /app/tools/auto_reenroll_user.py
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path


# Allow importing sibling modules when run from tools/
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from speaker_filter import SpeakerFilter, EMBEDDING_MODEL  # noqa: E402


MIN_DURATION = 30.0    # seconds — too short = unreliable embedding
MAX_DURATION = 600.0   # seconds — too long = batch processing risk
DEFAULT_N_SAMPLES = 5  # number of sessions to enroll from


def load_json(path: Path) -> dict | None:
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (FileNotFoundError, json.JSONDecodeError, OSError):
        return None


def find_candidates(recordings_dir: Path, limit: int) -> list[dict]:
    """Return qualifying session dicts, most-recent first."""
    candidates = []
    for day_dir in sorted(recordings_dir.iterdir(), reverse=True):
        if not day_dir.is_dir():
            continue
        for time_dir in sorted(day_dir.iterdir(), reverse=True):
            if not time_dir.is_dir():
                continue
            # audio_scene lives in session.json
            sess_json = load_json(time_dir / "session.json") or {}
            scene = sess_json.get("audio_scene") or {}
            if scene.get("scene_label_en") != "conversation":
                continue
            if (scene.get("music") or {}).get("detected"):
                continue

            # duration + num_speakers + segments live in transcript.json
            transcript = load_json(time_dir / "transcript.json")
            if not transcript:
                continue
            tsess = transcript.get("session") or {}
            duration = tsess.get("duration_seconds") or 0
            if duration < MIN_DURATION or duration > MAX_DURATION:
                continue
            num_sp = tsess.get("num_speakers")
            if num_sp is not None and num_sp != 1:
                continue
            segments = transcript.get("segments") or []
            usable_segs = [s for s in segments if (s.get("end", 0) - s.get("start", 0)) >= 0.5]
            if not usable_segs:
                continue

            audio_file = (transcript.get("session") or {}).get("audio_file", "audio.ogg")
            audio_path = time_dir / audio_file
            if not audio_path.exists():
                for ext in ("audio.ogg", "audio.wav"):
                    alt = time_dir / ext
                    if alt.exists():
                        audio_path = alt
                        break
                else:
                    continue

            candidates.append({
                "session_name": f"{day_dir.name}/{time_dir.name}",
                "audio_path": str(audio_path),
                "segments": usable_segs,
                "duration": duration,
                "scene_confidence": scene.get("scene_confidence", 0),
            })
            if len(candidates) >= limit:
                return candidates
    return candidates


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config-dir", default=os.environ.get("CONFIG_DIR", "/app/config"))
    ap.add_argument("--recordings-dir", default=os.environ.get("RECORDINGS_DIR", "/app/recordings"))
    ap.add_argument("--n-samples", type=int, default=DEFAULT_N_SAMPLES)
    ap.add_argument("--dry-run", action="store_true", help="Only list candidates; do not modify")
    args = ap.parse_args()

    hf_token = os.environ.get("HF_AUTH_TOKEN", "")
    if not hf_token:
        print("ERROR: HF_AUTH_TOKEN not set", file=sys.stderr)
        return 1

    sf = SpeakerFilter(config_dir=args.config_dir, hf_token=hf_token, device="cuda")

    # Find the user speaker
    user_speaker = next(
        (s for s in sf._data["speakers"] if s.get("is_user")),
        None,
    )
    if not user_speaker:
        print("ERROR: no speaker with is_user=True found in speakers.json", file=sys.stderr)
        return 1

    print(f"Target speaker: {user_speaker['id']} ({user_speaker.get('name')})")
    print(f"Current model in speakers.json: {sf._data.get('model')}")
    print(f"Runtime EMBEDDING_MODEL:        {EMBEDDING_MODEL}")
    print(f"Existing samples:               {len(user_speaker.get('samples', []))}")

    recordings_dir = Path(args.recordings_dir)
    candidates = find_candidates(recordings_dir, args.n_samples)

    print(f"\nFound {len(candidates)} candidate session(s):")
    for i, c in enumerate(candidates, 1):
        print(f"  {i}. {c['session_name']:40s} duration={c['duration']:6.1f}s  "
              f"scene_conf={c['scene_confidence']:.2f}  segments={len(c['segments'])}")

    if args.dry_run:
        print("\n(dry-run — no changes made)")
        return 0

    if not candidates:
        print("ERROR: no qualifying candidates found", file=sys.stderr)
        return 1

    # Clear existing samples (they were made with the old model)
    print(f"\nClearing {len(user_speaker.get('samples', []))} existing sample(s)...")
    user_speaker["samples"] = []
    user_speaker["embedding"] = None

    added = 0
    for c in candidates:
        print(f"  Enrolling from {c['session_name']}...")
        sample = sf.add_voiceprint(
            user_speaker["id"],
            c["audio_path"],
            c["segments"],
            session_name=c["session_name"],
        )
        if sample:
            added += 1
            print(f"    ✓ added sample {sample['id']} ({sample['duration']:.1f}s)")
        else:
            print(f"    ✗ failed")

    # Update model field
    sf._data["model"] = EMBEDDING_MODEL
    sf._save()

    final = next(s for s in sf._data["speakers"] if s["id"] == user_speaker["id"])
    print(f"\nEnrollment complete:")
    print(f"  samples: {len(final.get('samples', []))}")
    print(f"  has_embedding: {final.get('embedding') is not None}")
    print(f"  model in speakers.json: {sf._data['model']}")

    return 0 if added > 0 else 1


if __name__ == "__main__":
    sys.exit(main())
